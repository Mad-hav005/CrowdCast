// Build the payload the backend expects from a demo event object
export function eventToPayload(evt) {
  return {
    days_until_event: evt.days_until_event,
    event_hour: evt.event_hour,
    is_weekend: evt.is_weekend,
    day_of_week: evt.day_of_week,
    city: evt.city || null,
    state: evt.state || null,
    metro: evt.metro || null,
    timezone: evt.timezone || null,
    addressCountryCode: evt.country || null,
    listing_count: evt.listing_count,
    section_count: evt.section_count,
    section_group_count: evt.section_group_count,
    max_available_lot: evt.max_available_lot,
    avg_max_available_lot: evt.avg_max_available_lot,
    deal_rate: evt.deal_rate,
    ga_listing_rate: evt.ga_listing_rate,
    listing_count_prev: evt.listing_count_prev ?? null,
    listing_change: evt.listing_change ?? null,
    latitude: evt.latitude ?? null,
    longitude: evt.longitude ?? null,
  };
}

// Generate fake history snapshots for demo chart (varying days_until_event)
export function generateDemoHistory(evt) {
  const snaps = [];
  const baseDays = evt.days_until_event;
  for (let d = baseDays + 28; d >= baseDays; d -= 4) {
    const ratio = 1 - ((baseDays + 28 - d) / 28) * 0.4 * Math.random();
    snaps.push({
      daysUntil: d,
      label: `${d}d`,
      listings: Math.round(evt.listing_count_prev * ratio),
    });
  }
  return snaps;
}

